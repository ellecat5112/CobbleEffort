def inside_poly(x, y, pts):
    inside = False
    for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
        if (y0 > y) != (y1 > y) and x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
            inside = not inside
    return inside


def seg_dist(px, py, x0, y0, x1, y1):
    dx, dy = x1 - x0, y1 - y0
    t = max(0.0, min(1.0, ((px - x0) * dx + (py - y0) * dy) / (dx * dx + dy * dy or 1)))
    return math.hypot(px - (x0 + t * dx), py - (y0 + t * dy))


def icon(key):
    grid = [[None] * 16 for _ in range(16)]
    for sh in ICONS[key]:
        for y in range(16):
            for x in range(16):
                hit = False
                if sh[0] == "r":
                    hit = sh[1] <= x <= sh[3] and sh[2] <= y <= sh[4]
                elif sh[0] == "c":
                    hit = math.hypot(x - sh[1], y - sh[2]) <= sh[3]
                elif sh[0] == "l":
                    hit = seg_dist(x, y, sh[1], sh[2], sh[3], sh[4]) <= sh[5]
                elif sh[0] == "p":
                    hit = inside_poly(x + 0.5, y + 0.5, sh[1])
                if hit:
                    grid[y][x] = sh[-1]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y in range(16):
        for x in range(16):
            if grid[y][x] is None:
                if any(0 <= x + dx < 16 and 0 <= y + dy < 16 and grid[y + dy][x + dx] is not None
                       for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    px[x, y] = C["k"] + (255,)                 # the dark outline
                continue
            c = C[grid[y][x]]
            k = 1.08 if (x + y) < 12 else 0.92 if (x + y) > 20 else 1.0
            px[x, y] = tuple(max(0, min(255, int(v * k))) for v in c) + (255,)
    return img


def write_all(out: Path, keys):
    out.mkdir(parents=True, exist_ok=True)
    for k in keys:
        icon(k).save(out / f"rotom_{k}.png", optimize=True)
